// @vitest-environment jsdom
import { act } from 'react'
import { createRoot, type Root } from 'react-dom/client'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { ResearchExplorer } from './ResearchExplorer'
import type { ResearchRun, ResearchRequest } from '../shared/research-explorer'
let root: Root, host: HTMLDivElement
const run: ResearchRun = { id: 'test-run', createdAt: '2026-10-09T07:00:00Z', request: { mode: 'survey', topics: ['异常检测'], inspirations: ['多模态医疗推理'], publicationYears: 1, preprintMonths: 4, count: 5 }, status: 'complete', progress: '已完成', sources: [{ id: 'paper', title: 'Grounded anomaly detection', authors: 'A Researcher', date: '2026-08-01', venue: 'arXiv 预印本', group: 'preprint', roles: ['inspiration'], topics: ['多模态医疗推理'], url: 'https://arxiv.org/abs/2608.12345', abstract: 'Abstract', evidenceKind: 'abstract' }], items: [{ sourceId: 'paper', summary: '模型验证图像与报告的一致性。', method: '推理模型与验证器。', datasets: '独立数据划分。', evaluation: '基线比较。', contribution: 'uncertain', contributionReason: '只有摘要。', risks: '需排查训练测试重叠。', transfer: '可测试跨领域迁移。', evidence: [] }], overview: '领域方法谱系。', insights: ['推演：独立测试。', '推演：迁移验证。'], warnings: [] }
beforeEach(async () => {
  Object.defineProperty(globalThis, 'IS_REACT_ACT_ENVIRONMENT', { value: true, configurable: true })
  Object.defineProperty(window, 'singularity', { configurable: true, value: { research: { fields: vi.fn().mockResolvedValue([]), explorations: vi.fn().mockResolvedValue([]), deleteExploration: vi.fn().mockResolvedValue(undefined), updateExploration: vi.fn().mockResolvedValue({ ...run, status: 'collecting', progress: '正在检索' }), explore: vi.fn(async (request: ResearchRequest) => ({ ...run, request, status: 'collecting' })), cancelExploration: vi.fn().mockResolvedValue(undefined), importExploration: vi.fn().mockResolvedValue({ id: 'library-paper' }), openSource: vi.fn().mockResolvedValue(undefined) } } })
  host = document.createElement('div'); document.body.append(host); root = createRoot(host)
  await act(async () => { root.render(<ResearchExplorer/>) }); })
afterEach(async () => { await act(async () => { root.unmount() }); host.remove(); vi.restoreAllMocks() })
const click = async (selector: string) => act(async () => { host.querySelector<HTMLButtonElement>(selector)!.click() })
const pickTopic = async (name: string) => {
  const button = [...host.querySelectorAll<HTMLButtonElement>('.research-topic-presets button')].find((item) => item.textContent?.includes(name))
  await act(async () => { button!.click() })
}
describe('research discovery interaction', () => {
  it('starts a survey from the entry without showing a linked project', async () => {
    Object.assign(window.singularity, { knowledge: { projects: vi.fn().mockResolvedValue([{ id: 'project-a', title: 'Visual grounding project' }]) } })
    await act(async () => { root.unmount(); root = createRoot(host); root.render(<ResearchExplorer currentProjectId="project-a"/>) })
    expect(host.querySelector('[aria-label="检索关联研究项目"]')).toBeNull()
    expect(host.textContent).not.toContain('返回研究项目')
    expect(host.textContent).toContain('梳理领域')
    await click('.research-entry:first-child')
    expect(host.querySelector('form')?.textContent).toContain('领域')
    expect(host.querySelector('form')?.textContent).toContain('大语言模型')
    expect(host.querySelector('form')?.textContent).toContain('扩散模型')
    expect(host.querySelector('.research-topic-presets')?.textContent).toContain('异常检测')
    expect(host.querySelector('[aria-label="移除 异常检测"]')).toBeNull()
    expect(host.querySelector('form')?.textContent).not.toContain('多模态医疗推理')
    expect(host.querySelector('[aria-label="自定义核心领域"]')).not.toBeNull()
    await act(async () => { host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })) })
    expect(window.singularity.research.explore).toHaveBeenCalledWith(expect.objectContaining({ mode: 'survey', count: 10, projectId: undefined }))
  })
  it('can attach a paper already in the library to the current research project', async () => {
    Object.assign(window.singularity, { knowledge: { projects: vi.fn().mockResolvedValue([{ id: 'project-a', title: 'Current project', paperIds: [] }]) } })
    vi.mocked(window.singularity.research.explorations).mockResolvedValue([{ ...run, request: { ...run.request, mode: 'recommend', projectId: 'project-a' }, items: [{ ...run.items[0], libraryId: 'library-paper' }] }])
    vi.mocked(window.singularity.research.importExploration).mockResolvedValue({ id: 'library-paper' } as never)
    await act(async () => { root.unmount(); root = createRoot(host); root.render(<ResearchExplorer currentProjectId="project-a"/>) });     const button = host.querySelector<HTMLButtonElement>('.research-paper-card footer .research-action-wrap:last-child button')!
    expect(button.disabled).toBe(false); expect(button.getAttribute('aria-label')).toContain('加入此项目')
    await click('.research-paper-card footer .research-action-wrap:last-child button')
    expect(button.getAttribute('aria-label')).toContain('已在项目'); expect(button.disabled).toBe(true)
  })
  it('starts one study with the chosen recommendation count', async () => {
    await click('.research-entry:first-child')
    expect(host.querySelector('form')?.textContent).toContain('领域')
    await pickTopic('异常检测')
    await act(async () => { host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })) })
    expect(window.singularity.research.explore).toHaveBeenCalledWith(expect.objectContaining({ mode: 'survey', count: 10, topics: ['异常检测'], inspirations: [] }))
    expect(host.querySelector('form')).toBeNull()
    expect(host.querySelector('.research-run-status')).not.toBeNull()
    await click('[aria-label="取消任务"]')
    expect(window.singularity.research.cancelExploration).toHaveBeenCalledWith('test-run')
  })
  it('lets the recommendation count differ from the wider development summary', async () => {
    await click('.research-entry')
    const count = host.querySelector<HTMLSelectElement>('[aria-label="推荐论文数量"]')!
    expect([...count.options].map(option => option.value)).toEqual(['5', '10', '15', '20'])
    await act(async () => { count.value = '5'; count.dispatchEvent(new Event('change', { bubbles: true })) })
    await pickTopic('异常检测')
    await act(async () => { host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })) })
    expect(window.singularity.research.explore).toHaveBeenCalledWith(expect.objectContaining({ mode: 'survey', topics: ['异常检测'], count: 5, publicationYears: 2, preprintMonths: 24 }))
  })
  it('shows grouped compact cards, evidence limits, research insights and one-click import', async () => {
    vi.mocked(window.singularity.research.explorations).mockResolvedValue([{ ...run, sources: [...run.sources, { ...run.sources[0], id: 'older', title: 'Older language model result', date: '2026-06-01' }] }])
    await act(async () => { root.unmount(); root = createRoot(host); root.render(<ResearchExplorer/>) });         expect(host.textContent).toContain('顶会顶刊'); expect(host.textContent).toContain('arXiv 最新研究')
    expect(host.textContent).not.toContain('Older language model result')
    expect(host.textContent).toContain('仅摘要 · 待核验'); expect(host.textContent).toContain('局限')
    await click('.research-paper-card footer .research-action-wrap:last-child button')
    expect(window.singularity.research.importExploration).toHaveBeenCalledWith('test-run', 'paper')
    expect(host.querySelector('.research-paper-card footer .research-action-wrap:last-child button')?.getAttribute('aria-label')).toContain('已在论文库')
    expect(host.querySelector<HTMLButtonElement>('.research-paper-card footer .research-action-wrap:last-child button')!.disabled).toBe(true)
  })
  it('takes an explicit date range from the window dropdown instead of a separate switch', async () => {
    await click('.research-entry')
    const selects = host.querySelectorAll<HTMLSelectElement>('.research-options select')
    expect(selects[0].options).toHaveLength(6)
    expect(selects[1].options).toHaveLength(7)
    expect([...selects[0].options].at(-1)!.textContent).toBe('自定义')
    expect(host.querySelector('.research-window-toggle')).toBeNull()
    expect(host.querySelectorAll('.research-options input[type="date"]')).toHaveLength(0)
    await act(async () => { selects[0].value = '10'; selects[0].dispatchEvent(new Event('change', { bubbles: true })) })
    expect(selects[0].value).toBe('10')
    await act(async () => { selects[0].value = 'custom'; selects[0].dispatchEvent(new Event('change', { bubbles: true })) })
    expect(selects[0].value).toBe('custom')
    expect(selects[1].value).toBe('custom')
    expect(host.querySelectorAll('.research-options input[type="date"]')).toHaveLength(2)
    await act(async () => { selects[1].value = '6'; selects[1].dispatchEvent(new Event('change', { bubbles: true })) })
    expect(host.querySelectorAll('.research-options input[type="date"]')).toHaveLength(0)
    expect(selects[0].value).toBe('10')
    await act(async () => { selects[1].value = 'custom'; selects[1].dispatchEvent(new Event('change', { bubbles: true })) })
    await act(async () => { host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })) })
    expect(window.singularity.research.explore).toHaveBeenCalledWith(expect.objectContaining({ mode: 'survey', dateFrom: expect.stringMatching(/^\d{4}-\d{2}-\d{2}$/), dateTo: expect.stringMatching(/^\d{4}-\d{2}-\d{2}$/), publicationYears: 10 }))
  })
  it('links a delta follow-up run straight to the Delta tab', async () => {
    vi.mocked(window.singularity.research.explorations).mockResolvedValue([{ ...run, request: { ...run.request, delta: true, fieldId: 'field-1' } }])
    await act(async () => { root.unmount(); root = createRoot(host); root.render(<ResearchExplorer/>) });     expect(host.querySelector('[aria-label="查看 Delta 对比"]')).not.toBeNull()
  })
  it('imports every pending paper of a result in one action', async () => {
    vi.mocked(window.singularity.research.explorations).mockResolvedValue([run])
    await act(async () => { root.unmount(); root = createRoot(host); root.render(<ResearchExplorer/>) });         const bulk = host.querySelector<HTMLButtonElement>('.research-import-all')!
    expect(bulk.textContent).toContain('全部加入论文库')
    await click('.research-import-all')
    expect(window.singularity.research.importExploration).toHaveBeenCalledWith('test-run', 'paper')
    expect(host.querySelector('.research-import-all')).toBeNull()
  })
  it('deletes the selected history entry from the three-dot menu', async () => {
    vi.mocked(window.singularity.research.explorations).mockResolvedValue([run])
    const confirm = vi.spyOn(window, 'confirm').mockReturnValue(true)
    await act(async () => { root.unmount(); root = createRoot(host); root.render(<ResearchExplorer/>) })
    expect(host.querySelector('[aria-label="研究历史"]')).not.toBeNull()
    expect(host.querySelector('.research-history-menu')).toBeNull()
    await click('.research-history-more')
    expect(host.querySelector('.research-history-menu')?.textContent).toContain('删除这条梳理记录')
    await click('.research-history-menu button')
    await act(async () => {})
    expect(confirm).toHaveBeenCalled()
    expect(window.singularity.research.deleteExploration).toHaveBeenCalledWith('test-run')
    expect(host.querySelector('.research-history-menu')).toBeNull()
  })
  it('keeps the entry when the delete confirmation is dismissed', async () => {
    vi.mocked(window.singularity.research.explorations).mockResolvedValue([run])
    vi.spyOn(window, 'confirm').mockReturnValue(false)
    await act(async () => { root.unmount(); root = createRoot(host); root.render(<ResearchExplorer/>) })
    await click('.research-history-more')
    await click('.research-history-menu button')
    await act(async () => {})
    expect(window.singularity.research.deleteExploration).not.toHaveBeenCalled()
  })
  it('cannot delete a run that is still working', async () => {
    vi.mocked(window.singularity.research.explorations).mockResolvedValue([{ ...run, status: 'collecting' }])
    await act(async () => { root.unmount(); root = createRoot(host); root.render(<ResearchExplorer/>) })
    await click('.research-history-more')
    expect(host.querySelector<HTMLButtonElement>('.research-history-menu button')!.disabled).toBe(true)
  })
  it('appends newly published papers from the update panel above the result heading', async () => {
    vi.mocked(window.singularity.research.explorations).mockResolvedValue([run])
    await act(async () => { root.unmount(); root = createRoot(host); root.render(<ResearchExplorer/>) })
    expect(host.textContent).not.toContain('我的领域')
    expect(host.querySelector('.research-run-toolbar .research-update-trigger')?.textContent).toContain('更新领域')
    await click('.research-update-trigger')
    const span = host.querySelector<HTMLSelectElement>('[aria-label="更新时间范围"]')!
    expect([...span.options].map(option => option.value)).toEqual(['1', '3', '6', '12', '24', 'custom'])
    await act(async () => { span.value = '6'; span.dispatchEvent(new Event('change', { bubbles: true })) })
    const count = host.querySelector<HTMLSelectElement>('[aria-label="更新论文数量"]')!
    await act(async () => { count.value = '10'; count.dispatchEvent(new Event('change', { bubbles: true })) })
    await act(async () => { host.querySelector('.research-update-panel')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })) })
    const [id, options] = vi.mocked(window.singularity.research.updateExploration).mock.calls[0]
    expect(id).toBe('test-run')
    expect(options).toMatchObject({ count: 10 })
    expect(options.dateFrom).toMatch(/^\d{4}-\d{2}-\d{2}$/)
    expect(options.dateTo).toMatch(/^\d{4}-\d{2}-\d{2}$/)
    expect(host.querySelector('.research-update-panel')).toBeNull()
  })
  it('requires a full custom window before updating', async () => {
    vi.mocked(window.singularity.research.explorations).mockResolvedValue([run])
    await act(async () => { root.unmount(); root = createRoot(host); root.render(<ResearchExplorer/>) })
    await click('.research-update-trigger')
    const span = host.querySelector<HTMLSelectElement>('[aria-label="更新时间范围"]')!
    await act(async () => { span.value = 'custom'; span.dispatchEvent(new Event('change', { bubbles: true })) })
    expect(host.querySelectorAll('.research-update-panel input[type="date"]')).toHaveLength(2)
    expect(host.querySelector<HTMLButtonElement>('.research-update-panel footer button')!.disabled).toBe(true)
    await act(async () => { host.querySelector('.research-update-panel')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })) })
    expect(window.singularity.research.updateExploration).not.toHaveBeenCalled()
  })
})
